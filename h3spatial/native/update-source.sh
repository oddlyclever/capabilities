#!/bin/bash
# Re-vendor the H3 C source from a tagged upstream release, regenerate the agreement test fixtures from
# that release, and rewrite the provenance stamp.
# Usage: ./update-source.sh [h3-tag] [h3-java-tag]        e.g. ./update-source.sh v4.5.0 v4.5.0
#
# The vendored C is compiled for iOS only. The JVM and Android use Uber's own com.uber:h3 and
# com.uber:h3-android, which are built from h3-java; the h3-java tag given here is the release those
# artifacts must be at. The script checks that release was built against the same H3 tag, so every
# target runs the same H3, and refuses to continue otherwise. Nothing from h3-java is vendored.
#
# Vendored source is committed, so consumers need no network access or upstream checkout to build.
# Never hand-edit anything this script writes — it replaces each file wholesale, so a local edit is
# silently lost on the next update.
set -euo pipefail
DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
MODULE="$(dirname "$DIR")"
H3_TAG="${1:-v4.5.0}"
H3_JAVA_TAG="${2:-v4.5.0}"
H3_DEST="$DIR/h3lib"
H3_UPSTREAM="https://github.com/uber/h3"
H3_JAVA_UPSTREAM="https://github.com/uber/h3-java"

command -v python3 >/dev/null || { echo "ERROR: python3 is required to generate the test fixtures" >&2; exit 1; }

echo "=== h3spatial · vendoring H3 $H3_TAG, checking h3-java $H3_JAVA_TAG ==="
WORK="$(mktemp -d)"; trap 'rm -rf "$WORK"' EXIT
git -c advice.detachedHead=false clone --quiet --depth 1 --branch "$H3_TAG" "$H3_UPSTREAM" "$WORK/h3"
git -c advice.detachedHead=false clone --quiet --depth 1 --branch "$H3_JAVA_TAG" "$H3_JAVA_UPSTREAM" "$WORK/h3-java"
H3_SHA="$(git -C "$WORK/h3" rev-parse HEAD)"
H3_JAVA_SHA="$(git -C "$WORK/h3-java" rev-parse HEAD)"

H3_JAVA_BUILT_AGAINST="$(sed -n 's/^h3\.git\.reference=//p' "$WORK/h3-java/h3version.properties")"
if [ "$H3_JAVA_BUILT_AGAINST" != "$H3_TAG" ]; then
    echo "ERROR: h3-java $H3_JAVA_TAG is built against H3 $H3_JAVA_BUILT_AGAINST, not $H3_TAG." >&2
    echo "Pick the h3-java release whose h3version.properties names $H3_TAG." >&2
    exit 1
fi

rm -rf "$H3_DEST"; mkdir -p "$H3_DEST"
cp -R "$WORK/h3/src/h3lib/." "$H3_DEST/"
cp "$WORK/h3/VERSION" "$H3_DEST/VERSION"
# The generated header is a build output; CMake produces it from h3api.h.in.
rm -f "$H3_DEST/include/h3api.h"

# The agreement tests assert against Uber's own test data for this same release, so it is regenerated
# here too: expected values always match the vendored H3, never a previous one.
python3 "$DIR/generate-agreement-fixtures.py" "$WORK/h3/tests/inputfiles" \
    "$MODULE/src/commonTest/kotlin/UberH3Fixtures.kt" "$H3_TAG" "$H3_SHA"

cat > "$DIR/PROVENANCE" <<STAMP
# Provenance of the vendored H3 C source and the iOS static libraries built from it, and of the
# h3-java release the JVM and Android artifacts must match.
# Regenerated by native/update-source.sh — do not hand-edit.

upstream        = $H3_UPSTREAM
upstream_tag    = $H3_TAG
upstream_commit = $H3_SHA
vendored_path   = native/h3lib

h3_java_upstream = $H3_JAVA_UPSTREAM
h3_java_tag      = $H3_JAVA_TAG
h3_java_commit   = $H3_JAVA_SHA
h3_java_h3_tag   = $H3_JAVA_BUILT_AGAINST
STAMP

echo "Vendored $(find "$H3_DEST/lib" -name '*.c' | wc -l | tr -d ' ') H3 sources at $H3_TAG ($H3_SHA)."
echo "h3-java $H3_JAVA_TAG is built against $H3_JAVA_BUILT_AGAINST — matches."
echo "Set uberH3 in gradle/libs.versions.toml to ${H3_JAVA_TAG#v}, run ./build-natives.sh, and commit together."
