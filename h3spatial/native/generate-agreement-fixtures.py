#!/usr/bin/env python3
"""Generate the Uber agreement fixtures for :h3spatial's tests from H3's own test input files.

Usage: generate-agreement-fixtures.py <h3 tests/inputfiles dir> <output .kt> <h3 tag> <h3 commit>

Run by update-source.sh, so the expected values always come from the same H3 release as the vendored
C. The tests cannot read files on JS, wasmJs or iOS, so the data is embedded in Kotlin source; string
constants are chunked because the JVM limits a single constant to 65535 bytes.
"""
import glob
import os
import sys

inputs, output, tag, commit = sys.argv[1:5]
CHUNK = 50_000


def lines(name, limit=None):
    with open(os.path.join(inputs, name)) as f:
        rows = [line.strip() for line in f if line.strip()]
    return rows[:limit] if limit else rows


def cells(name, limit=None):
    """Boundary files: an index line, then '{', one 'lat lng' per vertex, then '}'."""
    out, current, verts = [], None, []
    for row in lines(name):
        if row == "{":
            verts = []
        elif row == "}":
            out.append(current + " " + ";".join(verts))
            if limit and len(out) >= limit:
                break
        elif " " in row:
            lat, lng = row.split()
            verts.append(lat + "," + lng)
        else:
            current = row
    return out


def names(pattern):
    return sorted(os.path.basename(p) for p in glob.glob(os.path.join(inputs, pattern)))


centers, boundaries, ics = [], [], []
# A sample per file rather than every row: the finer-resolution files hold thousands of cells each,
# and the resolution-0 set below already covers every base cell, including all twelve pentagons.
for n in names("bc*centers.txt"):
    centers += lines(n, 50)
for n in names("bc*cells.txt"):
    boundaries += cells(n, 20)
for n in names("rand*centers.txt"):
    centers += lines(n, 50)
for n in names("rand*cells.txt"):
    boundaries += cells(n, 20)
boundaries += cells("res00cells.txt") + cells("res01cells.txt", 150)
ics += lines("res00ic.txt") + lines("res01ic.txt")


def emit(name, rows):
    text = "\n".join(rows)
    chunks = [text[i:i + CHUNK] for i in range(0, len(text), CHUNK)]
    # Split only between rows so no row is cut across two constants.
    fixed, carry = [], ""
    for chunk in chunks:
        chunk = carry + chunk
        cut = chunk.rfind("\n")
        if cut == -1 or chunk is chunks[-1]:
            fixed.append(chunk)
            carry = ""
        else:
            fixed.append(chunk[:cut])
            carry = chunk[cut + 1:]
    if carry:
        fixed.append(carry)
    body = ",\n".join('    """' + c + '"""' for c in fixed)
    return f"internal val {name}: List<String> = listOf(\n{body},\n).flatMap {{ it.lines() }}\n"


with open(output, "w") as f:
    f.write(f"""// GENERATED by native/generate-agreement-fixtures.py from uber/h3 {tag} ({commit}),
// tests/inputfiles. Do not edit: native/update-source.sh regenerates it with the vendored H3 release.
//
// Derived from Uber's own H3 test input (Copyright Uber Technologies, Inc.), licensed under the Apache
// License 2.0. Modified: a subset of rows from each file is selected and reformatted into Kotlin string
// constants. See NOTICE.

/** `index lat lng` — the point, in degrees, lies in the cell. Longitudes may be written 0..360. */
{emit("uberCellCenters", centers)}
/** `index lat,lng;lat,lng;…` — the cell's boundary vertices in degrees, in H3's order. */
{emit("uberCellBoundaries", boundaries)}
/** `index lat lng` — the cell's centre in degrees. */
{emit("uberCellCentroids", ics)}""")

print(f"centers={len(centers)} boundaries={len(boundaries)} centroids={len(ics)} bytes={os.path.getsize(output)}")
