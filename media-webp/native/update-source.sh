#!/bin/bash
# Re-vendor libwebp from a tagged upstream release and rewrite the provenance stamp.
# Usage: ./update-source.sh [tag]        e.g. ./update-source.sh v1.6.0
#
# Only what the encoder build needs is kept: the library sources under src/ and sharpyuv/, and the licence,
# patent grant and authors list that must travel with anything built from them. Vendored source is committed, so
# consumers need no network access or upstream checkout. Never hand-edit anything this script writes — it replaces
# each file wholesale, so a local edit is silently lost on the next update.
#
# After updating, run ./build-natives.sh and commit the source, the stamp and the rebuilt libraries together.
set -euo pipefail
DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TAG="${1:-v1.6.0}"
DEST="$DIR/libwebp"
UPSTREAM="https://github.com/webmproject/libwebp"

echo "=== webp · vendoring libwebp $TAG ==="
WORK="$(mktemp -d)"; trap 'rm -rf "$WORK"' EXIT
git -c advice.detachedHead=false clone --quiet --depth 1 --branch "$TAG" "$UPSTREAM" "$WORK/libwebp"
SHA="$(git -C "$WORK/libwebp" rev-parse HEAD)"

rm -rf "$DEST"; mkdir -p "$DEST"
cp -R "$WORK/libwebp/src" "$WORK/libwebp/sharpyuv" "$DEST/"
cp "$WORK/libwebp/COPYING" "$WORK/libwebp/PATENTS" "$WORK/libwebp/AUTHORS" "$DEST/"
# The container libraries: metadata is written in Kotlin, so every target gets it, not only those with libwebp.
rm -rf "$DEST/src/mux" "$DEST/src/demux"
# Build files for upstream's own build systems; this module builds with ../CMakeLists.txt.
find "$DEST" \( -name 'Makefile*' -o -name '*.am' -o -name '*.pc.in' -o -name '*.rc' -o -name 'CMakeLists.txt' \) -delete

cat > "$DIR/PROVENANCE" <<STAMP
# Provenance of the vendored libwebp source and the native libraries built from it.
# Regenerated by native/update-source.sh — do not hand-edit.

upstream        = $UPSTREAM
upstream_tag    = $TAG
upstream_commit = $SHA
vendored_path   = native/libwebp
STAMP

echo "Vendored libwebp $TAG ($SHA): $(find "$DEST" -name '*.c' | wc -l | tr -d ' ') sources."
echo "Run ./build-natives.sh, then commit the source, PROVENANCE and the rebuilt libraries together."
